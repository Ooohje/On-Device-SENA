export const fillName = (text: string, name: string) => text.replace(/\{name\}/g, name);

// 오늘의 한 문장 (홈 화면 위젯·튜토리얼 'daily'): 날짜마다 다른 문장을 고른다. 이름이 들어가는 문장은 뺀다(위젯은 앱 밖에서 그려짐)
const DAILY_POOL = UNITS.flatMap((u) => u.sentences.filter((s) => !s.en.includes('{name}')).map((s) => ({ ...s, unit: u })));
export function dailySentence(date = new Date()) {
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
  return DAILY_POOL[((day * 37) % DAILY_POOL.length + DAILY_POOL.length) % DAILY_POOL.length]; // 37을 곱해 단원이 고르게 섞이게
}
